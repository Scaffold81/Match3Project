#nullable enable

namespace Match3.Core.Enums
{
    /// <summary>
    /// Тип блокирующего препятствия на ячейке доски.
    /// </summary>
    public enum ObstacleType
    {
        None,

        /// <summary>
        /// Лёд: гем заморожен, не двигается и не матчится.
        /// Снимается смежными матчами. 1–2 HP.
        /// </summary>
        Ice,

        /// <summary>
        /// Ящик: гема нет, клетка заблокирована, падение через неё невозможно.
        /// Снимается смежными матчами. 1–3 HP.
        /// </summary>
        Box,

        /// <summary>
        /// Цепь: гем виден. При HP=1 участвует в матче (одновременно снимает цепь).
        /// При HP>1 цепь снимается смежными матчами, после достижения 1 HP — матчем самого гема.
        /// 1–2 HP.
        /// </summary>
        Chain,

        /// <summary>
        /// Камень: неподвижный блок, аналогичен Box но с большим HP.
        /// Разбивается смежными матчами. Гема нет, блокирует падение.
        /// 2–4 HP.
        /// </summary>
        Rock,
    }
}
